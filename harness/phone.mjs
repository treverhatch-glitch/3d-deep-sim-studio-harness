if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  const argv = process.argv.slice(2);
  const i = argv.indexOf('--by');
  const by = i >= 0 ? argv[i + 1] : actor();
  const cmd = argv[0] || 'status';

  if (cmd === 'on') {
    const r = phoneOn(by);
    if (!r.ok) { console.error(r.message); process.exit(1); }
    console.log(`Phone access enabled. Use this one-time code to log in from your phone:\n\n  ${r.code}\n\nIt expires at ${new Date(r.expiresAt).toLocaleTimeString()}.`);
  } else if (cmd === 'off') {
    phoneOff(by); console.log('Phone access disabled and all sessions revoked.');
  } else if (cmd === 'new-code') {
    const r = newCode(by);
    if (!r.ok) { console.error(r.message); process.exit(1); }
    console.log(`New one-time code:\n\n  ${r.code}\n\nExpires at ${new Date(r.expiresAt).toLocaleTimeString()}.`);
  } else if (cmd === 'revoke') {
    revokeSessions(by); console.log('All active phone sessions revoked.');
  } else if (cmd !== 'status') {
    console.log('Usage: npm run phone -- on|off|new-code|revoke --by <name> | status');
    process.exit(1);
  } else {
    const cfg = readPhone();
    if (cfg.on) {
      console.log(`Phone access is ON (enabled by ${cfg.by} at ${new Date(cfg.at).toLocaleString()}).`);
      if (cfg.codeHash) console.log(`A pairing code is active and expires at ${new Date(cfg.codeExpiresAt).toLocaleTimeString()}.`);
    } else {
      console.log('Phone access is OFF.');
    }
  }
}
