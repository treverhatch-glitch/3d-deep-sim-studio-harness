#!/usr/bin/env node
/**
 * harness/phone.mjs — secure phone access to the War Room hub (2.30d).
 * This module enables a developer to access the local War Room server from their phone on the
 * same LAN or Tailscale network. It provides a simple, secure login flow using a one-time
 * pairing code, avoiding the need to handle the hub's API token on a mobile device.
 *
 *   npm run phone -- on --by <dev>
 *   npm run phone -- off | status | revoke | new-code --by <dev>
 */
import fs from 'node:fs';
import path from 'node:path';
import { randomBytes, scryptSync, createHash, timingSafeEqual } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { STUDIO_STATE_DIR, emitEvent, actor } from './event.mjs';

const PHONE_DIR = path.join(STUDIO_STATE_DIR, 'phone');
const PHONE_FILE = path.join(PHONE_DIR, 'phone.json');
const SESSIONS_FILE = path.join(PHONE_DIR, 'sessions.json');
const LIMITS_FILE = path.join(PHONE_DIR, 'limits.json');
const CODE_ALPHABET = '23456789ABCDEFGHJKMNPQRSTUVWXYZ';
const SCRYPT_PARAMS = { N: 16384, r: 8, p: 1, maxmem: 32 * 1024 * 1024 };
const FILE_MODE = 0o600;

const readJson = (file) => { try { return JSON.parse(fs.readFileSync(file, 'utf8')); } catch { return {}; } };
const writeJson = (file, data) => {
  fs.mkdirSync(path.dirname(file), { recursive: true, mode: 0o700 });
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n', { mode: FILE_MODE });
};

export const readPhone = () => readJson(PHONE_FILE);
const readSessions = () => readJson(SESSIONS_FILE);
const readLimits = () => readJson(LIMITS_FILE);

const generateCode = (len = 8) => Array.from(randomBytes(len)).map(b => CODE_ALPHABET[b % CODE_ALPHABET.length]).join('');
const hash = (data) => createHash('sha256').update(data).digest('hex');

function createNewCode(cfg, by) {
  const code = generateCode();
  const salt = randomBytes(16).toString('hex');
  const codeHash = scryptSync(code, salt, 64, SCRYPT_PARAMS).toString('hex');
  const codeExpiresAt = new Date(Date.now() + 15 * 60000).toISOString();
  const newCfg = { ...cfg, by, at: new Date().toISOString(), codeHash, salt, codeExpiresAt };
  writeJson(PHONE_FILE, newCfg);
  emitEvent({ type: 'phone.code_generated', agent: by, msg: `New phone pairing code generated by ${by}` });
  return { code, expiresAt: codeExpiresAt };
}

export function phoneOn(by) {
  if (!by) return { ok: false, message: 'Say who: --by <name>.' };
  const { code, expiresAt } = createNewCode({ on: true }, by);
  return { ok: true, code, expiresAt };
}

export function phoneOff(by) {
  if (!by) return { ok: false, message: 'Say who: --by <name>.' };
  writeJson(PHONE_FILE, { on: false, by, at: new Date().toISOString() });
  try { fs.rmSync(SESSIONS_FILE); } catch {}
  emitEvent({ type: 'phone.off', agent: by, msg: `Phone access turned off by ${by}` });
  return { ok: true };
}

export function newCode(by) {
  if (!by) return { ok: false, message: 'Say who: --by <name>.' };
  const cfg = readPhone();
  if (!cfg.on) return { ok: false, message: 'Phone access is not on.' };
  const { code, expiresAt } = createNewCode(cfg, by);
  return { ok: true, code, expiresAt };
}

export function revokeSessions(by) {
  if (!by) return { ok: false, message: 'Say who: --by <name>.' };
  try { fs.rmSync(SESSIONS_FILE); } catch {}
  emitEvent({ type: 'phone.sessions_revoked', agent: by, msg: `All phone sessions revoked by ${by}` });
  return { ok: true };
}

export function login(code, { ip = 'unknown', ua = '', now = Date.now() } = {}) {
  const cfg = readPhone();
  const limits = readLimits();
  const ipLimit = limits[ip] || { failures: 0, lockedUntil: 0 };

  if (ipLimit.lockedUntil && ipLimit.lockedUntil <= now) Object.assign(ipLimit, { failures: 0, lockedUntil: 0 });
  if (ipLimit.lockedUntil > now) {
    return { ok: false, error: 'Too many failed attempts.', retryAfterSec: Math.ceil((ipLimit.lockedUntil - now) / 1000) };
  }

  const fail = (error) => {
    ipLimit.failures++;
    if (ipLimit.failures >= 5) ipLimit.lockedUntil = now + 15 * 60000;
    limits[ip] = ipLimit;
    writeJson(LIMITS_FILE, limits);
    emitEvent({ type: 'phone.login_failed', agent: 'harness', msg: `Phone login failed for ip ${ip}: ${error}`, meta: { ip } });
    return { ok: false, error };
  };

  if (!cfg.on || !cfg.codeHash) return fail('Phone access is off or no code is set.');
  if (Date.parse(cfg.codeExpiresAt) < now) return fail('Pairing code has expired.');

  const userCodeHash = scryptSync(String(code || '').trim().toUpperCase(), cfg.salt, 64, SCRYPT_PARAMS);
  const storedCodeHash = Buffer.from(cfg.codeHash, 'hex');
  if (!timingSafeEqual(userCodeHash, storedCodeHash)) return fail('Invalid code.');

  // Success
  delete cfg.codeHash; delete cfg.salt; delete cfg.codeExpiresAt;
  writeJson(PHONE_FILE, cfg);
  delete limits[ip];
  writeJson(LIMITS_FILE, limits);

  const sid = randomBytes(32).toString('base64url');
  const csrf = randomBytes(16).toString('base64url');
  const expiresAt = new Date(now + 12 * 3600 * 1000);
  const sessions = Object.fromEntries(Object.entries(readSessions()).filter(([, v]) => Date.parse(v.expiresAt) > now));
  sessions[hash(sid)] = {
    csrfHash: hash(csrf),
    ip,
    ua: ua.slice(0, 60),
    createdAt: new Date(now).toISOString(),
    expiresAt: expiresAt.toISOString(),
    lastSeen: new Date(now).toISOString(),
  };
  writeJson(SESSIONS_FILE, sessions);
  emitEvent({ type: 'phone.login', agent: cfg.by, msg: `Phone login successful for ${cfg.by}`, meta: { ip } });
  return { ok: true, sid, csrf, expiresAt };
}

export function checkSession(sid, { csrf = null, write = false, now = Date.now() } = {}) {
  const cfg = readPhone();
  if (!cfg.on) return { ok: false, reason: 'Phone access is off.' };

  const sessions = readSessions();
  const session = sid ? sessions[hash(String(sid))] : null;
  if (!session) return { ok: false, reason: 'Session not found.' };
  if (Date.parse(session.expiresAt) < now) return { ok: false, reason: 'Session expired.' };

  if (write) {
    if (!csrf) return { ok: false, reason: 'CSRF token missing for write operation.' };
    if (!timingSafeEqual(Buffer.from(hash(String(csrf))), Buffer.from(String(session.csrfHash)))) return { ok: false, reason: 'CSRF token mismatch.' };
  }

  if (now - Date.parse(session.lastSeen) > 60000) {
    session.lastSeen = new Date(now).toISOString();
    writeJson(SESSIONS_FILE, sessions);
  }
  return { ok: true };
}

export function sessionCookie(sid, expiresAt) {
  const maxAge = Math.floor((expiresAt.getTime() - Date.now()) / 1000);
  const secure = process.env.STUDIO_PHONE_SECURE_COOKIE === '1' ? '; Secure' : '';
  return `phone_sid=${sid}; HttpOnly; SameSite=Strict; Path=/; Max-Age=${maxAge}${secure}`;
}

export function parseCookieSid(cookieHeader) {
  return cookieHeader?.match(/phone_sid=([^;]+)/)?.[1] || '';
}

